// Aula 01 - Variáveis Primitivas

console.log("Aprendendo Variáveis!") // Console.log é o único comando que pode mostrar no terminal alguma coisa}

let idade = 20
let cliente = "Você" // A escolha do nome da variável é de livre escolha, porém toda escolha é tratada como código, qualquer texto deve ser colocado em ""
console.log(idade) // Mostra o que a variável está guardando no terminal

// Concatenação (Juntar pedaços de texto usando o +)
console.log("Meu nome é " +cliente+ "\n" ) // Para ter um espaço após essa aclopamento, seria ("texto " + variável)
console.log("Eu tenho " +idade +" anos \n "  ) // É possível só colocar a informação(20) sem uma variável, mas por fins de praticidade e manutenção, colocar variáveis
// Para colocar mais informações na frente da variável, se for texto, é + " texto"

console.log("Me chamo " +cliente+ " e eu tenho " +idade+ " anos!")
// Acima usou todos os conceitos aprendidos, colocar variável junto com textos, para mudar a variável basta mudar seu conteúdo
